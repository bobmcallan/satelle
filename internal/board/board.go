// Package board folds a story's agent messages and their marks into the one
// answer the CLI, the in-process verbs and the web panel all show: what each
// message's state is, and whether it is overdue (sty_73c9aa10).
//
// A message is an agent_message ledger row. Every change to its state is a
// separate, append-only message_mark row naming it; the message's state is the
// latest mark's, and waiting when it has none. Nothing here writes — the verbs
// append, this package only reads — and it imports the ledger alone, so any
// reader can fold without pulling in the verb layer. The wire contract for a
// hosted board is api/board.proto; this package is its local owner.
package board

import (
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/bobmcallan/satelle/internal/ledger"
)

// State is a message's delivery state. Overdue is not a state: it is derived at
// read time from the deadline and the state, and never stored.
type State string

const (
	// Waiting is a message nothing has marked yet.
	Waiting State = "waiting"
	// Delivered is a message that reached its addressee. Not "read": only
	// Answered proves the addressee acted.
	Delivered State = "delivered"
	// Answered is a message the addressee replied to or acknowledged.
	Answered State = "answered"
	// Undeliverable is a message that cannot reach its addressee.
	Undeliverable State = "undeliverable"
)

// States lists the four states in lifecycle order.
var States = []State{Waiting, Delivered, Answered, Undeliverable}

// Valid reports whether s is one of the four states.
func (s State) Valid() bool {
	for _, v := range States {
		if s == v {
			return true
		}
	}
	return false
}

// MaxBody is the largest message body, in bytes. It is the cap api/board.proto
// publishes, so a message that posts locally can post to a hosted board.
const MaxBody = 64 << 10

// Kind says what a message is addressed to.
type Kind string

const (
	// KindStory is the work: whoever holds the story.
	KindStory Kind = "story"
	// KindRole is a role on the story.
	KindRole Kind = "role"
	// KindSession is one named session, by id.
	KindSession Kind = "session"
	// KindAll is everyone.
	KindAll Kind = "all"
)

const (
	storyPrefix   = "story:"
	sessionPrefix = "session:"
	allAddress    = "*"
)

// Address resolves an --to argument into the stored `to` token on a story: ""
// and "*" address everyone, "story" the work, "role:<r>" a role, "session:<id>"
// one session, and any other bare word a role, which is what `to` always meant.
// A role is stored as its bare name and the rest keep their prefix, so every
// reader that matches `to` against a role set keeps working unchanged.
func Address(arg, storyID string) (string, error) {
	arg = strings.TrimSpace(arg)
	switch {
	case arg == "" || arg == allAddress:
		return allAddress, nil
	case arg == "story":
		if strings.TrimSpace(storyID) == "" {
			return "", fmt.Errorf("board: --to story needs the story id")
		}
		return storyPrefix + storyID, nil
	case strings.HasPrefix(arg, "role:"):
		r := strings.TrimSpace(strings.TrimPrefix(arg, "role:"))
		if r == "" || r == allAddress {
			return "", fmt.Errorf("board: --to role: needs a role name")
		}
		return r, nil
	case strings.HasPrefix(arg, sessionPrefix):
		if strings.TrimSpace(strings.TrimPrefix(arg, sessionPrefix)) == "" {
			return "", fmt.Errorf("board: --to session: needs a session id")
		}
		return arg, nil
	}
	return arg, nil
}

// Addressee splits a stored `to` token into what it addresses and the value
// (role name, session id, story id; empty for everyone).
func Addressee(to string) (Kind, string) {
	switch {
	case to == "" || to == allAddress:
		return KindAll, ""
	case strings.HasPrefix(to, storyPrefix):
		return KindStory, strings.TrimPrefix(to, storyPrefix)
	case strings.HasPrefix(to, sessionPrefix):
		return KindSession, strings.TrimPrefix(to, sessionPrefix)
	}
	return KindRole, to
}

// NewID returns a fresh message id, msg_<8hex>. Posting is idempotent on it, so
// it is generated by the sender, never by whoever stores the message.
func NewID() string {
	var b [4]byte
	if _, err := rand.Read(b[:]); err != nil {
		// crypto/rand does not fail on a supported platform; fall back to time so
		// a message is still recorded rather than refused.
		return fmt.Sprintf("msg_%08x", uint32(time.Now().UnixNano()))
	}
	return "msg_" + hex.EncodeToString(b[:])
}

// ParseDeadline reads a --deadline: a Go duration counted from now ("30m"), or
// an RFC3339 instant. The result is absolute UTC, the form stored.
func ParseDeadline(s string, now time.Time) (time.Time, error) {
	s = strings.TrimSpace(s)
	if s == "" {
		return time.Time{}, nil
	}
	if d, err := time.ParseDuration(s); err == nil {
		if d <= 0 {
			return time.Time{}, fmt.Errorf("board: --deadline %q must be in the future", s)
		}
		return now.UTC().Add(d), nil
	}
	t, err := time.Parse(time.RFC3339, s)
	if err != nil {
		return time.Time{}, fmt.Errorf("board: --deadline %q is neither a duration (30m) nor RFC3339", s)
	}
	return t.UTC(), nil
}

// Envelope is the part of an agent_message payload this feature adds to the
// original from/to/cc/body: who sent it and from where, the id it is marked
// under, and the optional reply link and deadline. verb.AgentMessage embeds it,
// so the stored payload and the folded view read one definition.
type Envelope struct {
	// MsgID is the message's own id (msg_<8hex>). Rows written before the board
	// existed carry none; they are identified by their ledger id.
	MsgID string `json:"msg_id,omitempty"`
	// InReplyTo is the message this one answers.
	InReplyTo string `json:"in_reply_to,omitempty"`
	// Deadline is the instant after which an unanswered message is overdue.
	Deadline *time.Time `json:"deadline,omitempty"`
	// FromSessionID, FromSessionName and FromLocation identify the sender. Each
	// is empty when it could not be resolved. The name is for display only: it
	// changes with the engaged story, the id does not.
	FromSessionID   string `json:"from_session_id,omitempty"`
	FromSessionName string `json:"from_session_name,omitempty"`
	FromLocation    string `json:"from_location,omitempty"`
}

// Message is one agent message with its state folded in.
type Message struct {
	ID      string
	StoryID string
	From    string
	// To is the stored address token (see Address); Kind and Value are its parts.
	To    string
	Kind  Kind
	Value string
	Cc    string
	Body  string

	Envelope

	State State
	// AnswerID is the reply that answered the message, when a mark named one.
	AnswerID string
	// CreatedAt is when the message was posted; UpdatedAt when its state last
	// changed (CreatedAt when it never has).
	CreatedAt time.Time
	UpdatedAt time.Time
}

// ID returns the id a message is marked under: its msg_ id, else, for a row
// written before the board existed, its ledger id.
func ID(e ledger.Entry) string {
	var p struct {
		MsgID string `json:"msg_id"`
	}
	if len(e.Payload) > 0 && json.Unmarshal(e.Payload, &p) == nil && p.MsgID != "" {
		return p.MsgID
	}
	return e.ID
}

// Transcript reports whether an agent_message row is the rework relay's own
// transcript (cc "*"): conversation about the work, not a message anybody is
// waiting on, so the board does not list it.
func Transcript(e ledger.Entry) bool {
	var p struct {
		Cc string `json:"cc"`
	}
	return len(e.Payload) > 0 && json.Unmarshal(e.Payload, &p) == nil && p.Cc == "*"
}

// MarkPayload is the payload of a message_mark row. The row's Refs name the
// message: {"message": "<msg id>"}.
type MarkPayload struct {
	State       State  `json:"state"`
	AnswerID    string `json:"answer_id,omitempty"`
	BySessionID string `json:"by_session_id,omitempty"`
}

// MarkRefs is the Refs of a message_mark row for message id.
func MarkRefs(id string) json.RawMessage {
	b, _ := json.Marshal(map[string]string{"message": id})
	return b
}

// MarkedMessage is the message id a message_mark row names ("" if it names none).
func MarkedMessage(e ledger.Entry) string {
	var r struct {
		Message string `json:"message"`
	}
	if len(e.Refs) > 0 && json.Unmarshal(e.Refs, &r) == nil {
		return r.Message
	}
	return ""
}

// Fold turns agent_message rows and message_mark rows into messages, oldest
// first. A message with no mark is waiting; otherwise the latest mark wins, in
// ledger order (created_at, ties in the order given). A mark that names no
// message here, or carries an unknown state, changes nothing. Rows of other
// kinds are skipped.
func Fold(msgs, marks []ledger.Entry) []Message {
	byID := make(map[string]int, len(msgs))
	out := make([]Message, 0, len(msgs))
	for _, e := range msgs {
		if e.Kind != ledger.KindAgentMessage {
			continue
		}
		m := decode(e)
		byID[m.ID] = len(out)
		out = append(out, m)
	}
	ordered := make([]ledger.Entry, 0, len(marks))
	for _, e := range marks {
		if e.Kind == ledger.KindMessageMark {
			ordered = append(ordered, e)
		}
	}
	sort.SliceStable(ordered, func(i, j int) bool { return ordered[i].CreatedAt.Before(ordered[j].CreatedAt) })
	for _, e := range ordered {
		i, ok := byID[MarkedMessage(e)]
		if !ok {
			continue
		}
		var p MarkPayload
		if json.Unmarshal(e.Payload, &p) != nil || !p.State.Valid() {
			continue
		}
		out[i].State, out[i].AnswerID, out[i].UpdatedAt = p.State, p.AnswerID, e.CreatedAt
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].CreatedAt.Before(out[j].CreatedAt) })
	return out
}

func decode(e ledger.Entry) Message {
	var p struct {
		From string `json:"from"`
		To   string `json:"to"`
		Cc   string `json:"cc"`
		Body string `json:"body"`
		Envelope
	}
	if len(e.Payload) > 0 {
		_ = json.Unmarshal(e.Payload, &p)
	}
	if p.Body == "" {
		p.Body = e.Body
	}
	kind, value := Addressee(p.To)
	return Message{
		ID: ID(e), StoryID: e.StoryID, From: p.From, To: p.To, Kind: kind, Value: value, Cc: p.Cc, Body: p.Body,
		Envelope: p.Envelope, State: Waiting, CreatedAt: e.CreatedAt, UpdatedAt: e.CreatedAt,
	}
}

// Overdue reports whether m is overdue at now: it has a deadline that has passed
// and it has not been answered. It is derived at read time and never stored; a
// message with no deadline is never overdue.
func Overdue(m Message, now time.Time) bool {
	return m.Deadline != nil && now.After(*m.Deadline) && m.State != Answered
}
