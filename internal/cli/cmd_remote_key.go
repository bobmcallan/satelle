// `satelle remote key|identity|check` manage how a remote proves itself to
// satelle.dev when it reads its secrets, and check that it can (sty_0b1c72a9). A
// remote's identity is an Ed25519 key — its private half held by the host's secret
// store, only the public half registered on satelle.dev — or a platform's workload
// identity. satelle writes neither half of a key to any file of its own.
package cli

import (
	"context"
	"fmt"
	"io"
	"sort"
	"strings"
	"time"

	"github.com/spf13/cobra"

	"github.com/bobmcallan/satelle/internal/hosted"
	"github.com/bobmcallan/satelle/internal/remotedef"
	"github.com/bobmcallan/satelle/internal/remotesign"
)

// expiryWarnWindow is how far ahead of a secret's expiry `remote check` starts
// warning.
const expiryWarnWindow = 14 * 24 * time.Hour

func newRemoteKeyCmd() *cobra.Command {
	var server, publicKey string
	key := &cobra.Command{
		Use:   "key",
		Short: "Create, register or rotate the Ed25519 key a remote signs its secret reads with",
		Long: `A remote proves itself to satelle.dev with an Ed25519 key. Its private half is
printed once and is yours to put in the host's secret store, as the environment
variable the definition names under identity.key; satelle never writes it. Only
the public half is registered on satelle.dev. All three verbs address the remote by
remote_id and refuse a remote that binds a workload identity instead.`,
	}
	create := &cobra.Command{
		Use:   "create <remote>",
		Short: "Generate a key, register its public half and print the private half once",
		Long: `Generates an Ed25519 key, registers the public half on satelle.dev for the remote
named by remote_id, and prints the private half once, with where to put it: the
host's secret store, as the environment variable the definition names under
identity.key. The key is registered before it is shown, and satelle keeps neither
half in any file. Needs satelle login.`,
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return runRemoteKeyNew(cmd, args[0], server, false)
		},
	}
	rotate := &cobra.Command{
		Use:   "rotate <remote>",
		Short: "Generate a new key and replace the registered one; the old key stops verifying at once",
		Long: `Like create, for a remote that already has a key: satelle.dev replaces the
registered public key in one write, so every signature the old key made fails from
then on. Update the host's secret store with the new private key before the next
run. Needs satelle login.`,
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return runRemoteKeyNew(cmd, args[0], server, true)
		},
	}
	reg := &cobra.Command{
		Use:   "register <remote> --public-key <base64>",
		Short: "Register a public key you made elsewhere",
		Long: `Registers the standard base64 of a 32-byte Ed25519 public key for the remote. Use
it for a key generated by your host's own tooling; satelle receives only the public half.`,
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return runRemoteKeyRegister(cmd, args[0], server, publicKey)
		},
	}
	reg.Flags().StringVar(&publicKey, "public-key", "", "the public key, standard base64 (required)")
	_ = reg.MarkFlagRequired("public-key")
	key.AddCommand(create, rotate, reg)
	key.PersistentFlags().StringVar(&server, "server", "", "Hosted server URL (overrides the configured machine hosted server)")
	return key
}

// keyTarget is the remote a key verb addresses: its id, after the checks every
// key verb makes before any request.
func keyTarget(name string) (remotedef.Definition, string, error) {
	def, err := loadRemoteDef(name)
	if err != nil {
		return def, "", err
	}
	id, err := def.RequireRemoteID(name)
	if err != nil {
		return def, "", err
	}
	if def.Identity.OIDC != nil {
		return def, "", fmt.Errorf("remote %s binds a workload identity (identity.oidc); it takes no key — remove identity.oidc and run satelle remote identity clear first", name)
	}
	return def, id, nil
}

func runRemoteKeyNew(cmd *cobra.Command, name, server string, rotating bool) error {
	def, id, err := keyTarget(name)
	if err != nil {
		return err
	}
	if def.Identity.Key == "" {
		return fmt.Errorf("remote %s: identity.key is not set; name the host environment variable that will hold the private key, then run this again", name)
	}
	client, err := secretClient(server)
	if err != nil {
		return err
	}
	seed, public, err := remotesign.NewKey()
	if err != nil {
		return err
	}
	// Registered first: a key satelle.dev did not accept is never shown.
	info, err := client.SetRemoteKey(cmd.Context(), id, public)
	if err != nil {
		return fmt.Errorf("remote %s: register key: %w", name, err)
	}
	out := cmd.OutOrStdout()
	verb := "registered"
	if rotating {
		verb = "rotated to"
	}
	fmt.Fprintf(out, "remote %s (%s): %s the public key %s (set %s)\n", name, id, verb, info.Fingerprint, info.SetAt)
	if rotating {
		fmt.Fprintln(out, "the previous key no longer verifies; update the host's secret store with the key below")
	}
	fmt.Fprintf(out, "\nPrivate key — shown once; satelle does not keep it:\n\n%s\n\n", seed)
	fmt.Fprintf(out, "Put it in your host's secret store as the environment variable %s (remote %s reads it from there).\n", def.Identity.Key, name)
	return nil
}

func runRemoteKeyRegister(cmd *cobra.Command, name, server, public string) error {
	_, id, err := keyTarget(name)
	if err != nil {
		return err
	}
	if _, err := remotesign.Fingerprint(public); err != nil {
		return fmt.Errorf("--public-key is %w", err)
	}
	client, err := secretClient(server)
	if err != nil {
		return err
	}
	info, err := client.SetRemoteKey(cmd.Context(), id, public)
	if err != nil {
		return fmt.Errorf("remote %s: register key: %w", name, err)
	}
	fmt.Fprintf(cmd.OutOrStdout(), "remote %s (%s): registered the public key %s (set %s)\n", name, id, info.Fingerprint, info.SetAt)
	return nil
}

func newRemoteIdentityCmd() *cobra.Command {
	var server string
	identity := &cobra.Command{
		Use:   "identity",
		Short: "Bind or unbind a platform workload identity as the way a remote proves itself",
		Long: `Instead of a key, a remote on a platform that issues workload identity tokens can
prove itself with one: nothing secret is stored on the host. set binds the issuer
and subject the definition declares under identity.oidc; clear removes the binding.
satelle names no platform: the issuer, subject and token command are the
definition's own.`,
	}
	set := &cobra.Command{
		Use:   "set <remote>",
		Short: "Bind the issuer and subject the definition declares under identity.oidc",
		Long: `Registers the definition's identity.oidc issuer and subject on satelle.dev for
the remote named by remote_id. satelle.dev then accepts a token that platform
issues for a run's audience in place of a signature. A remote has a key or a
binding, never both: the server refuses a bind while a key is registered. Needs
satelle login.`,
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			def, err := loadRemoteDef(args[0])
			if err != nil {
				return err
			}
			id, err := def.RequireRemoteID(args[0])
			if err != nil {
				return err
			}
			if def.Identity.OIDC == nil {
				return fmt.Errorf("remote %s declares no identity.oidc to bind", args[0])
			}
			client, err := secretClient(server)
			if err != nil {
				return err
			}
			o := def.Identity.OIDC
			if err := client.SetRemoteIdentity(cmd.Context(), id, o.Issuer, o.Subject); err != nil {
				return fmt.Errorf("remote %s: bind identity: %w", args[0], err)
			}
			fmt.Fprintf(cmd.OutOrStdout(), "remote %s (%s): bound identity %s as %s\n", args[0], id, o.Issuer, o.Subject)
			return nil
		},
	}
	clear := &cobra.Command{
		Use:   "clear <remote>",
		Short: "Remove the remote's workload identity binding",
		Long: `Removes the workload identity binding from the remote named by remote_id on
satelle.dev; tokens its platform issued stop being accepted at once. Removing an
absent binding is not an error. Needs satelle login.`,
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			def, err := loadRemoteDef(args[0])
			if err != nil {
				return err
			}
			id, err := def.RequireRemoteID(args[0])
			if err != nil {
				return err
			}
			client, err := secretClient(server)
			if err != nil {
				return err
			}
			if err := client.DeleteRemoteIdentity(cmd.Context(), id); err != nil {
				return fmt.Errorf("remote %s: clear identity: %w", args[0], err)
			}
			fmt.Fprintf(cmd.OutOrStdout(), "remote %s (%s): identity binding removed\n", args[0], id)
			return nil
		},
	}
	identity.AddCommand(set, clear)
	identity.PersistentFlags().StringVar(&server, "server", "", "Hosted server URL (overrides the configured machine hosted server)")
	return identity
}

// checkFinding is one thing `remote check` found. A failing one makes the check
// exit non-zero; a warning is advice.
type checkFinding struct {
	Fail bool
	Msg  string
}

// secretLister is the part of the hosted client `remote check` reads.
type secretLister interface {
	ListSecrets(ctx context.Context, scope, workspace string) ([]hosted.SecretMeta, error)
}

// checkRemoteSecrets finds what stops def's declared secrets reaching a run: a
// remote_id not set, a story command that would not read them, a secret missing on
// satelle.dev or not granted to the remote, and one lapsing within 14 days. With no
// remote_id nothing is asked of the server.
func checkRemoteSecrets(ctx context.Context, def remotedef.Definition, lister secretLister, now time.Time) ([]checkFinding, error) {
	if !def.HasSecrets() {
		return nil, nil
	}
	var out []checkFinding
	fail := func(f string, a ...any) { out = append(out, checkFinding{true, fmt.Sprintf(f, a...)}) }
	warn := func(f string, a ...any) { out = append(out, checkFinding{false, fmt.Sprintf(f, a...)}) }

	if def.Host.StoryCommand != "" && !def.StoryDrives() {
		fail("host.story_command does not run `satelle story drive`, the command that reads a run's secrets")
	}
	if def.RemoteID == "" {
		fail("remote_id is not set; register the remote on satelle.dev, then set remote_id = \"rmt_…\" in its definition")
		return out, nil
	}
	type scopeAt struct{ scope, workspace string }
	held := map[scopeAt]map[string]hosted.SecretMeta{}
	for _, d := range def.Secret {
		s := scopeAt{d.Scope, d.Workspace}
		if _, done := held[s]; done {
			continue
		}
		metas, err := lister.ListSecrets(ctx, d.Scope, d.Workspace)
		if err != nil {
			return out, fmt.Errorf("list %s secrets: %w", d.Scope, err)
		}
		held[s] = map[string]hosted.SecretMeta{}
		for _, m := range metas {
			held[s][m.Key] = m
		}
	}
	for _, d := range def.Secret {
		m, ok := held[scopeAt{d.Scope, d.Workspace}][d.Key]
		switch {
		case !ok || !m.HasValue:
			fail("secret %s (%s): missing on satelle.dev; run satelle secret push", d.Key, d.Scope)
			continue
		case !containsString(m.Readers, def.RemoteID):
			fail("secret %s (%s): not granted to %s; run satelle secret push", d.Key, d.Scope, def.RemoteID)
		}
		exp, has := m.Expiry()
		if !has {
			exp, has = d.ExpiresAt()
		}
		switch {
		case has && (m.Expired || !exp.After(now)):
			warn("secret %s (%s): expired %s", d.Key, d.Scope, exp.Format("2006-01-02"))
		case has && exp.Sub(now) <= expiryWarnWindow:
			warn("secret %s (%s): expires %s, in %d day(s)", d.Key, d.Scope, exp.Format("2006-01-02"), int(exp.Sub(now).Hours()/24))
		}
	}
	return out, nil
}

func newRemoteCheckCmd() *cobra.Command {
	var server string
	check := &cobra.Command{
		Use:   "check <remote>",
		Short: "Check that the remote's declared secrets can reach a run",
		Long: `Reports, per declared secret, whether satelle.dev holds it, whether it is granted
to the remote and whether it lapses within 14 days (a warning); and whether the
definition sets remote_id and runs its stories with satelle story drive. Exits
non-zero when a secret is missing or ungranted, the story command would not read
secrets, or remote_id is not set. Expiry only warns. Needs satelle login.`,
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return runRemoteCheck(cmd, args[0], server)
		},
	}
	check.Flags().StringVar(&server, "server", "", "Hosted server URL (overrides the configured machine hosted server)")
	return check
}

func runRemoteCheck(cmd *cobra.Command, name, server string) error {
	def, err := loadRemoteDef(name)
	if err != nil {
		return err
	}
	out := cmd.OutOrStdout()
	if !def.HasSecrets() {
		fmt.Fprintf(out, "remote %s: no [[secret]] declared; nothing to check\n", name)
		return nil
	}
	var lister secretLister
	if def.RemoteID != "" {
		client, err := secretClient(server)
		if err != nil {
			return err
		}
		lister = client
	}
	findings, err := checkRemoteSecrets(cmd.Context(), def, lister, time.Now())
	printCheck(out, name, findings)
	if err != nil {
		return err
	}
	failed := 0
	for _, f := range findings {
		if f.Fail {
			failed++
		}
	}
	if failed > 0 {
		return fmt.Errorf("remote %s: %d problem(s) would stop its secrets reaching a run", name, failed)
	}
	if len(findings) == 0 {
		fmt.Fprintf(out, "remote %s: secrets ok (%s)\n", name, strings.Join(secretKeys(def), ", "))
	}
	return nil
}

func printCheck(out io.Writer, name string, findings []checkFinding) {
	for _, f := range findings {
		level := "WARN"
		if f.Fail {
			level = "FAIL"
		}
		fmt.Fprintf(out, "%s  remote %s: %s\n", level, name, f.Msg)
	}
}

func secretKeys(def remotedef.Definition) []string {
	keys := make([]string, len(def.Secret))
	for i, d := range def.Secret {
		keys[i] = d.Key
	}
	sort.Strings(keys)
	return keys
}
