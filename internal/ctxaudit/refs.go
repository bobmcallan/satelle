// refs.go — the satelle references a context names, and whether each resolves.
//
// A reference is either a [[name]] wikilink or a backticked `satelle-…` name.
// The wikilink resolver is wikilink.go and is shared with `satelle validate`;
// what this file adds is the backticked form, the retired-name test, and the
// "named but nothing wires it" test. It decides nothing about what a context
// SHOULD name — it only reports a name that points at nothing live.
package ctxaudit

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/bobmcallan/satelle/internal/config"
)

// backtickNameRe matches a code span that is, in its entirety, a satelle
// artifact name. A span with any other character in it (`satelle-<object>-review`,
// `satelle hook context`, a path) is prose about syntax, not a reference.
var backtickNameRe = regexp.MustCompile("`(satelle-[a-z0-9]+(?:-[a-z0-9]+)*)`")

// RefKind classifies a reference problem.
type RefKind string

const (
	// RefUnresolved: the name resolves to no artifact of any kind, or is retired.
	RefUnresolved RefKind = "unresolved"
	// RefUnwired: the name is a skill that exists but nothing wires.
	RefUnwired RefKind = "unwired"
)

// RefProblem is one reference that points at nothing live. Where is the
// referring file, Ref the reference as written.
type RefProblem struct {
	Kind   RefKind
	Where  string
	Ref    string
	Detail string
}

// RefEnv is what a reference is resolved against.
type RefEnv struct {
	// Names is every artifact name of any kind (Catalog).
	Names map[string]bool
	// Skills is the subset of Names that are skills.
	Skills map[string]bool
	// Wired is the skills a route step, reviewer, gate, hook, summary, advisor or
	// task references.
	Wired map[string]bool
}

// BacktickNames returns the distinct backticked `satelle-…` names in body, in
// order of first appearance. Fenced blocks are masked (a fence SHOWS examples);
// inline spans are kept, since a backticked name is one.
func BacktickNames(body string) []string {
	var out []string
	seen := map[string]bool{}
	for _, m := range backtickNameRe.FindAllStringSubmatch(MaskFenced(body), -1) {
		if seen[m[1]] {
			continue
		}
		seen[m[1]] = true
		out = append(out, m[1])
	}
	return out
}

// CheckRefs reports every reference in body that points at nothing live. self
// is the referring artifact's own name, which is never reported against itself.
// [[name]] resolution is Dangling's; this adds the backticked form, retired
// names (reported as unresolved even when a stale copy still exists), and
// skills that exist but nothing wires.
func CheckRefs(body, where, self string, env RefEnv) []RefProblem {
	var out []RefProblem
	reported := map[string]bool{}
	add := func(kind RefKind, ref, name, detail string) {
		key := string(kind) + "\x00" + name
		if reported[key] {
			return
		}
		reported[key] = true
		out = append(out, RefProblem{Kind: kind, Where: where, Ref: ref, Detail: detail})
	}

	for _, target := range DanglingTargets(body, env.Names) {
		add(RefUnresolved, "[["+target+"]]", target, "names nothing that resolves"+RetirementSuffix(target))
	}
	check := func(name, ref string) {
		if name == self {
			return
		}
		if e, ok := config.LookupRetired(name); ok {
			add(RefUnresolved, ref, name, "was "+config.FormatRetirementMessage(name, e))
			return
		}
		if !env.Names[name] {
			add(RefUnresolved, ref, name, "names no skill, principle, workflow, task or document")
			return
		}
		if env.Skills[name] && !env.Wired[name] {
			add(RefUnwired, ref, name, "is a skill that no route step, reviewer, gate, hook, summary, advisor, consult or task wires")
		}
	}
	for _, name := range LinkTargets(body) {
		// A wikilink already reported as dangling is not judged twice.
		if env.Names[name] {
			check(name, "[["+name+"]]")
		}
	}
	for _, name := range BacktickNames(body) {
		check(name, "`"+name+"`")
	}
	return out
}

// StaleIndex reports every entry of documents/index.md whose document does not
// exist. The index is regenerated by reindex, so an entry for a deleted document
// is a stale index, not an authored claim.
func StaleIndex(dataDir string) []string {
	dir := filepath.Join(dataDir, "documents")
	raw, err := os.ReadFile(filepath.Join(dir, "index.md"))
	if err != nil {
		return nil
	}
	var out []string
	seen := map[string]bool{}
	for _, m := range indexEntryRe.FindAllStringSubmatch(string(raw), -1) {
		target := strings.TrimSpace(m[1])
		if target == "" || seen[target] || strings.Contains(target, "://") || strings.HasPrefix(target, "#") {
			continue
		}
		seen[target] = true
		if _, serr := os.Stat(filepath.Join(dir, filepath.FromSlash(target))); serr != nil {
			out = append(out, fmt.Sprintf("documents/index.md lists %q, which does not exist under documents/", target))
		}
	}
	return out
}

// indexEntryRe matches a list entry of the generated index: `* [Title](file.md)`.
var indexEntryRe = regexp.MustCompile(`(?m)^\s*[*-]\s+\[[^\]]*\]\(([^)\s]+)\)`)
